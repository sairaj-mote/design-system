const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = relativePath => fs.readFileSync(path.join(root, relativePath), 'utf8');
const write = (relativePath, content) => fs.writeFileSync(path.join(root, relativePath), content);
const hash = content => crypto.createHash('sha256').update(content).digest('hex');
const rgb = hex => hex.replace('#', '').match(/.{2}/g).map(value => Number.parseInt(value, 16)).join(', ');

const tokenSource = read('website/tokens/tokens.json');
const componentSource = read('components/components.js');
const utilitySource = read('main_UI.js');
const docsCssSource = read('website/css/main.css');
const docsRuntimeSource = read('website/js/docs-runtime.js');
const docsEngineSource = read('website/js/design-system.js');
const indexSource = read('website/index.html');
const tokens = JSON.parse(tokenSource);

const colorScale = (name, values) => Object.entries(values)
    .map(([step, definition]) => `  --color-${name}-${step}: ${definition.hex};`)
    .join('\n');

const css = `/* Generated by scripts/build-design-system.js from tokens/tokens.json. Do not edit. */
/* token-source-sha256: ${hash(tokenSource)} */

:root {
${colorScale('primary', tokens.color.brand.primary)}
${colorScale('secondary', tokens.color.brand.secondary)}
${colorScale('neutral', tokens.color.neutral)}

  --font-display: ${tokens.typography.families.display.stack};
  --font-body: ${tokens.typography.families.body.stack};
  --font-mono: ${tokens.typography.families.mono.stack};
${tokens.typography.scale.map(token => `  --text-${token.name}: ${token.size};`).join('\n')}
${tokens.spacing.scale.map(token => `  --${token.name}: ${token.rem};`).join('\n')}
${Object.entries(tokens.radius).map(([name, token]) => `  --radius-${name}: ${token.value};`).join('\n')}
${Object.entries(tokens.shadow).map(([name, token]) => `  --shadow-${name}: ${token.value};`).join('\n')}
${Object.entries(tokens.motion.duration).map(([name, token]) => `  --duration-${name}: ${token.ms}ms;`).join('\n')}
  --ease-linear: ${tokens.motion.easing.linear};
  --ease-base: ${tokens.motion.easing.ease};
  --ease-out: ${tokens.motion.easing['ease-out']};
  --ease-spring: ${tokens.motion.easing.spring};
  --bp-mobile: ${tokens.breakpoints.mobile.max};
  --bp-tablet: ${tokens.breakpoints.tablet.max};
}

body {
  --accent-color: ${tokens.color.theme.accent.light};
  --theme-accent-color: ${tokens.color.theme.accent.light};
  --secondary-color: ${tokens.color.theme.secondary.light};
  --text-color: ${rgb(tokens.color.theme.text.light)};
  --theme-text-rgb: ${rgb(tokens.color.theme.text.light)};
  --foreground-color: ${rgb(tokens.color.theme.foreground.light)};
  --theme-foreground-rgb: ${rgb(tokens.color.theme.foreground.light)};
  --background-color: ${rgb(tokens.color.theme.background.light)};
  --danger-color: ${rgb(tokens.color.semantic.danger.light)};
  --green: ${tokens.color.semantic.success.light};
  --green-rgb: ${rgb(tokens.color.semantic.success.light)};
  --danger-rgb: ${rgb(tokens.color.semantic.danger.light)};
  --warning-rgb: ${rgb(tokens.color.semantic.warning.light)};
  --on-accent: #ffffff;
}

body[data-theme="dark"] {
  --accent-color: ${tokens.color.theme.accent.dark};
  --theme-accent-color: ${tokens.color.theme.accent.dark};
  --secondary-color: ${tokens.color.theme.secondary.dark};
  --text-color: ${rgb(tokens.color.theme.text.dark)};
  --theme-text-rgb: ${rgb(tokens.color.theme.text.dark)};
  --foreground-color: ${rgb(tokens.color.theme.foreground.dark)};
  --theme-foreground-rgb: ${rgb(tokens.color.theme.foreground.dark)};
  --background-color: ${rgb(tokens.color.theme.background.dark)};
  --danger-color: ${rgb(tokens.color.semantic.danger.dark)};
  --green: ${tokens.color.semantic.success.dark};
  --green-rgb: ${rgb(tokens.color.semantic.success.dark)};
  --danger-rgb: ${rgb(tokens.color.semantic.danger.dark)};
  --warning-rgb: ${rgb(tokens.color.semantic.warning.dark)};
  --on-accent: #0b3a3c;
}
`;

const runtime = {
    color: {
        brand: [
            { label: 'Primary · Teal', group: 'primary', base: '600', note: 'Brand base · light-mode accent' },
            { label: 'Secondary · Amber', group: 'secondary', base: '500', note: 'Highlights & attention' }
        ],
        primary: Object.entries(tokens.color.brand.primary).map(([step, token]) => [step, token.hex, token.role]),
        secondary: Object.entries(tokens.color.brand.secondary).map(([step, token]) => [step, token.hex, token.role]),
        neutral: Object.entries(tokens.color.neutral).map(([step, token]) => [step, token.hex, token.role]),
        semantic: Object.entries(tokens.color.semantic).map(([name, token]) => ({ name: `${name[0].toUpperCase()}${name.slice(1)}`, ...token, usage: token.role })),
        theme: Object.entries(tokens.color.theme).map(([name, token]) => ({ name: `${name[0].toUpperCase()}${name.slice(1)}`, ...token, usage: token.role }))
    },
    type: {
        families: Object.entries(tokens.typography.families).map(([name, token]) => ({
            name: name === 'display' ? 'Poppins' : name === 'body' ? 'Roboto' : 'Roboto Mono',
            token: `--font-${name}`,
            stack: token.stack,
            usage: token.usage
        })),
        scale: tokens.typography.scale.map(token => ({
            ...token,
            name: token.name === 'display' ? 'Display' : token.name.toUpperCase(),
            lh: token.lineHeight,
            family: token.family,
            sample: token.name === 'display' ? 'The design system' : token.name === 'h1' ? 'Almost before we knew it' : token.name === 'h2' ? 'Building on primitives' : token.name === 'h3' ? 'Components, not pages' : token.name === 'h4' ? 'Section heading' : token.name === 'h5' ? 'Overline label' : token.name === 'body' ? 'The quick brown fox jumps over the lazy dog and keeps on going to test the line length comfortably.' : token.name === 'small' ? 'Helper text and captions' : '0x8F 12,480,000 tokens'
        }))
    },
    spacing: tokens.spacing.scale,
    radius: Object.entries(tokens.radius).map(([name, token]) => ({ name, ...token })),
    shadow: Object.entries(tokens.shadow).map(([name, token]) => ({ name, ...token })),
    motion: {
        duration: Object.entries(tokens.motion.duration).map(([name, token]) => ({ name, ...token })),
        easing: Object.entries(tokens.motion.easing).map(([name, value]) => ({ name, value, usage: name === 'spring' ? 'Delightful entrances, popups' : name === 'ease-out' ? 'Elements leaving the screen, standard' : 'Default browser curve, safe fallback' }))
    },
    breakpoints: Object.entries(tokens.breakpoints).map(([name, token]) => ({ name: `${name[0].toUpperCase()}${name.slice(1)}`, range: token.max ? `${token.min} – ${token.max}` : `≥ ${token.min}`, usage: token.usage })),
    zIndex: Object.entries(tokens.zIndex).map(([name, value]) => ({ name: name.replace(/([A-Z])/g, ' $1').replace(/^./, char => char.toUpperCase()), value, usage: name === 'base' ? 'Default content' : name === 'header' ? 'App header / sticky bars' : name === 'notification' ? 'Toast drawer' : 'Modals & popups (increments per open)' }))
};

write('website/tokens/tokens.css', css);
write('website/js/tokens-runtime.js', `/* Generated by scripts/build-design-system.js from tokens/tokens.json. Do not edit. */\n/* token-source-sha256: ${hash(tokenSource)} */\nwindow.RMDS_TOKENS = ${JSON.stringify(runtime, null, 2)};\n`);
write('website/js/components.js', `/* Generated by scripts/build-design-system.js from components/components.js. Do not edit. */\n/* component-source-sha256: ${hash(componentSource)} */\n${componentSource}`);
write('components/components.min.js', `/* Generated by scripts/build-design-system.js from components/components.js. Do not edit. */\n/* component-source-sha256: ${hash(componentSource)} */\n${componentSource}`);
write('main_UI.min.js', `/* Generated by scripts/build-design-system.js from main_UI.js. Do not edit. */\n/* utility-source-sha256: ${hash(utilitySource)} */\n${utilitySource}`);
[
    'Layouts/boxes layout/js',
    'Layouts/many sections layout/js',
    'Layouts/sidebar layout/js',
    'Layouts/tabs layout/js'
].forEach(layoutPath => {
    write(`${layoutPath}/components.min.js`, `/* Generated by scripts/build-design-system.js from components/components.js. Do not edit. */\n/* component-source-sha256: ${hash(componentSource)} */\n${componentSource}`);
    write(`${layoutPath}/main_UI.js`, `/* Generated by scripts/build-design-system.js from main_UI.js. Do not edit. */\n/* utility-source-sha256: ${hash(utilitySource)} */\n${utilitySource}`);
});
const assetVersions = {
    'tokens/tokens.css': hash(tokenSource).slice(0, 12),
    'css/main.css': hash(docsCssSource).slice(0, 12),
    'js/tokens-runtime.js': hash(tokenSource).slice(0, 12),
    'js/components.js': hash(componentSource).slice(0, 12),
    'js/docs-runtime.js': hash(docsRuntimeSource).slice(0, 12),
    'js/design-system.js': hash(docsEngineSource).slice(0, 12)
};
const versionedIndex = Object.entries(assetVersions).reduce((content, [asset, version]) => {
    const escapedAsset = asset.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const tag = asset.endsWith('.css') ? 'link' : 'script';
    const attribute = tag === 'link' ? 'href' : 'src';
    return content.replace(new RegExp(`(<${tag}[^>]*${attribute}="${escapedAsset})(?:\\?v=[^\"]*)?(\")`, 'g'), `$1?v=${version}$2`);
}, indexSource);
write('website/index.html', versionedIndex);
console.log('Built design-system token and component artifacts.');
